function sBand(s: number): '9-10' | '7-8' | '4-6' | '2-3' | '1' {
  if (s >= 9) return '9-10'
  if (s >= 7) return '7-8'
  if (s >= 4) return '4-6'
  if (s >= 2) return '2-3'
  return '1'
}
function oBand(o: number): '8-10' | '6-7' | '4-5' | '2-3' | '1' {
  if (o >= 8) return '8-10'
  if (o >= 6) return '6-7'
  if (o >= 4) return '4-5'
  if (o >= 2) return '2-3'
  return '1'
}
function dBand(d: number): '7-10' | '5-6' | '2-4' | '1' {
  if (d >= 7) return '7-10'
  if (d >= 5) return '5-6'
  if (d >= 2) return '2-4'
  return '1'
}

