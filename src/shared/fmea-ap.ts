/** S·O·D(각 1~10) → 조치우선순위 H/M/L. 하나라도 비면 null. */
export function computeActionPriority(
  s: number | null | undefined,
  o: number | null | undefined,
  d: number | null | undefined
): FmeaActionPriority | null {
  if (s == null || o == null || d == null) return null
  if (s < 1 || s > 10 || o < 1 || o > 10 || d < 1 || d > 10) return null
  return TABLE[sBand(s)][oBand(o)][dBand(d)]
}
