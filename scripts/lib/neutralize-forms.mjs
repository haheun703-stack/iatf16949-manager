/** 양식 이름 기계 정리 */
export function cleanName(code, name) {
  if (RENAME_FORMS[code]) return RENAME_FORMS[code]
  let s = String(name)
  s = s.replace(/^\(\s*\)\s*(사업부|년)\s*/, '') // "(   )사업부 개인별…" / "(    )년 경영검토…"
  s = s.replace(/^년\s+/, '연간 ') // "년 사내외 교육훈련 계획서"
  s = s.replace(/\s*\(\s*\)\s*_?(갑지)\s*$/, ' (갑지)') // "… () 갑지" / "()_갑지"
  s = s.replace(/\s*\(\s*\)(\s*_\S+)?\s*$/, '') // 꼬리 "()" / " ()" / "()_품질"
  s = s.replace(/\s*\(-[^)]*\)\s*$/, '') // "(-AM)" "(-조6)" "(-필라넥)" "(-01)"
  s = s.replace(/\s+/g, ' ').trim()
  return s
}

