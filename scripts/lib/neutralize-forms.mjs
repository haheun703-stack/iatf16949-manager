function stripDevSentences(s) {
  // 문장 분리: ". " 또는 문말 "." — 괄호 안 마침표는 드물어 단순 분할로 충분(결과는 before/after 로 전수 대조)
  const parts = s.split(/(?<=\.)\s+/)
  const kept = parts.filter((p) => !DEV_SENTENCE_RE.test(p))
  return kept.join(' ')
}

function tidy(s) {
  return s
    .replace(/\(\s*\)/g, '')
    .replace(/\s*[—–-]\s*$/g, '')
    .replace(/^\s*[—–-]\s*/g, '')
    .replace(/\s+\./g, '.')
    .replace(/\.\.+/g, '.')
    .replace(/\s+,/g, ',')
    .replace(/\s{2,}/g, ' ')
    .replace(/\s+·\s*$/g, '')
    .trim()
}

/** description 중립화 — null 이면 NULL 적재 */
export function cleanDescription(code, desc) {
  if (REWRITE_DESC[code]) return REWRITE_DESC[code]
  if (!desc) return null
  if (PLACEHOLDER_RE.test(desc)) return null
  let s = String(desc).replace(/\r?\n/g, ' ')
  if (REG_DOC_RE.test(s)) return '규정 문서(열람형) — 작성 양식이 아닌 규정 본문 등록 항목. 본문은 문서관리에서 등록·개정합니다.'
  let refDoc = false
  if (REF_DOC_RE.test(s)) {
    refDoc = true
    s = s.replace(REF_DOC_RE, '')
  }
  s = s.replace(CP_GAP_RE, '')
  s = s.replace(HEADER_RE, '')
  s = s.replace(PAREN_REF_RE, '')
  s = s.replace(/^보강 = /, '')
  s = stripDevSentences(s)
  s = tidy(s)
  if (!s) return refDoc ? '열람형(참조 문서) — 작성 양식이 아닌 참조 문서입니다.' : null
  if (!/[.!?]$/.test(s)) s += '.'
  return refDoc ? `열람형(참조 문서) — ${s}` : s
}

