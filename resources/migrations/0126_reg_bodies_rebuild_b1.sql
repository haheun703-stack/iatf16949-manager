5.4 표준의 등록
5.4.1 등록
등록주관팀장은 제정, 개정 및 폐지의 승인이 완료된 표준에 대하여 "회사표준관리
대장"에 등록하고 표준번호를 부여한다. 세부방법은 [부표1,2]에 따른다.
5.4.2 시행일자
표준의 시행일자는 승인일로부터 10일후를 원칙으로 하되 승인권자의 결정에 따라
변경할 수 있다.
5.4.3 원본보관
등록주관팀장은 표준원본을 보관하며, 표준이 개정된 경우, 구판 사본은 폐기하고,
구판 원본은 필요시 등록주관팀에서 "구본"으로 표기하여 보관한다.
5.5 사본 발행 및 배포
(1) 품질보증팀장은 회사표준 배포시 "회사표준관리대장"에 배포현황을 기록하고, 대장
사본을 첨부하여 배포한다. 단, 기술표준은 등록 주관팀장이 "기술표준관리대장"에
배포 현황을 기록하고, 접수팀은 팀별로 표준현황 목록을 작성하여 관리한다.
(2) 표준 복제 및 배포시에는 유효본 식별과 무단 복제의 통제를 위하여 회사 로고가
인쇄된 용지를 사용하거나 표지에 “관리본” 스탬프를 날인하여 배포한다.
(3) 전 임직원은 주관팀의 사전승인 없이 표준의 무단복제를 하여서는 안된다.
(4) 표준이 일부 개정된 경우 개정내용 요약을 표준서 표지에 기재하고 최근 변경부분에는
글씨체를 변경하여 식별 가능토록 한다. (예, 작업조건 변경)
(5) 표준 배포단위는 표준별 업무 해당 팀장으로 한다.
(6) 구판 표준은 신판 배포와 동시에 자체 폐기토록 하거나 배포자가 회수, 폐기한다.
표준관리 주관팀장은 구판 표준의 폐기를 확인하여야 한다.
5.6 활용
5.6.1 표준의 주지
각 팀장은 관련표준에 대하여 팀원에게 철저히 교육시키고 기록을 유지한다.
5.6.2 표준의 준수
표준은 제반업무의 기준으로서 반드시 준수되어야 하며, 승인권자의 승인없이 변경
될 수 없다. 단, 업무수행중 긴급한 사유로 표준의 준수가 곤란한 경우, 해당팀장은
승인권자의 서면승인으로 예외적 업무집행을 할 수 있으나 여타의 안건에 대하여는
표준에 따라 처리하여야 한다.
5.7 개정 및 폐기
(1) 표준의 개정 및 폐기는 제정절차에 따른다.
(2) 표준에 대하여 이의나 개선 필요성을 제기하고자 하는 팀이나 개인은 개정 초안을
작성하여 등록주관팀에 제출할 수 있다.
이를 접수한 경우 등록주관팀은 세부내용을 파악하고 필요시 표준 제개정을 추진하며,
그 결과를 요청자에게 통보한다.
5.8 표준의 취급
(1) 표준은 대외비로 관리한다.
(2) 표준의 사외반출은 대표이사의 사전승인을 받아야 한다.

