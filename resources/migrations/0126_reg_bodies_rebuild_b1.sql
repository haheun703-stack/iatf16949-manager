(6) 조직 구조/인적자원/시스템 및 운영방식/재무 구조 등 내부 이슈
5.1.4 각 팀은 Risk 분석 결과를 사업계획에 반영하여야 하며, 사업계획 실행 중 목표
달성에 영향을 끼칠 수 있는 변동이나 이슈가 발생된 경우 Risk 분석을 재 실시한다.
5.2 리스크 파악
5.2.1 각 팀은 파악된 이슈, 주요 변화 요소 및 성과에 중대한 영향을 미치는 프로세스
등에 대하여 Risk 파악을 실시한다.
5.2.2 Risk 파악은 업무/프로세스에 있어 그 목적의 미 달성, 고객 불만족, 효율성 저하,
재산/이익 측면의 손실 발생, 직원 안전/건강 또는 사기저하 등을 유발할 수 있는
기술적 위협, 자연 재해, 의도된 위협을 포함한다.
5.2.3 Risk 분석 시 잠재/실제 리콜, 필드 반송, 수리, 불만, 폐기 및 모든 재작업으로부터
의 습득교훈이 포함되도록 하여야 한다.
5.2.4 Risk 파악 시에는 정상 상황 뿐만 아니라 비 정상 상황에서 발생되는 요소도 포함
하여야 한다.
5.2.5 Risk 파악 시 Risk와 그 원인 및 영향이 혼동되지 않도록 구분하여야 한다.
(예) 프로세스: 자금관리
Risk : 단기 자금 경색
원인: 수금 또는 자금조달과 지출의 불일치에 의한 자금 지출 불능 발생
영향: 임금/구입 대금 등 지급 지연에 의한 신용 저하, 조직 이미지 실추
대응(단기): 수금 계획, 자금계획(월, 주) 수립 및 운영
대응(장기): 단기 자금 차입 축소 전략/계획 수립
5.3 리스크 메커니즘 규정
5.3.1 각 팀은 Risk 항목 별로 Risk가 발생/전개되는 과정(Mechanism) 을 파악하여야
하며 이를 위하여 발생원인과 영향/결과를 파악하여 정리한다.
5.3.2 원인 규명 시에는 “5why, 계통도법” 등의 방식을 이용하여, 발생 과정과 원인을
파악한다
5.3.3 Risk 에 따른 영향/결과(Consequence)를 다음을 포함하여 파악한다.
(1) 고객에게 미치는 영향
(2) 회사의 손익/수익성에 미치는 영향
(3) 내,외부 이해관계자에게 미치는 영향
(4) 제품 품질 및 납기에 미치는 영향
(5) 제품/서비스 사용 및 유지에 미치는 영향 등
(6) 회사 이미지/평판에 미치는 영향
5.3.4 파악된 내용은 “부정적 사항(위험)과 긍정적 사항(기회)”로 나누어 분류하며.
“RISK 분석표”에 등록한다.
5.4 리스크 추정
5.4.1 각 팀은 Risk의 영향, 발생 빈도, 감지가능성/돌발성에 대한 의사소통과 합리적인
수준 평가를 위하여 수준 등급을 정하고 점수를 부여하여야 한다.
5.4.2 각 팀은 Risk의 영향/결과에 대하여 심각한 정도를 판단하고 이를 점수화 한다.
Risk 심각도의 점수화 기준은 부표 1에 따른다
5.4.3 각 팀은 Risk의 원인에 대하여 발생 빈도를 추정하고 이를 점수화 한다.
Risk 발생도의 점수화 기준은 부표 2에 따른다
5.4.4 각 팀은 Risk의 감지 가능 정도와 돌발적 발생 및 확산 정도에 대하여 긴급도를
추정하고 이를 점수화 한다. Risk 긴급도의 점수화 기준은 부표 3에 따른다
5.5 리스크 분석
5.5.1 각 팀은 Risk 영향(심각도), 발생 가능성(발생도), 감지 가능성(긴급도)을 곱하여
위험지수(RPN=Risk Priority Number)를 산출한다.
5.5.2 위험 지수 산출 결과 25점 이상이거나 개별 항목 중 5점이 있는 경우 중점관리 대상
으로 분류하고 조치 방안을 수립하여 관리한다.
5.5.3 Risk 분석 결과는 RISK 분석표에 기록 후 총무팀에 제출, 총무팀은 경영진에 보고한다.
5.6 리스크 대응방안 수립
5.6.1 각 팀은 각 Risk 항목에 대하여 대응방안을 수립한다.
대응 방안에는 수용, 전가, 통제, 회피, 활용, 강화, 비상계획이 있을 수 있다
5.6.2 대응 방안은 위험과 기회 또는 이들 모두에 해당되는 경우로 구분하여 수립한다.
세부사항은 부표 4에 따른다
5.6.3 각 팀은 위험에 대한 대응방안이 “통제(Control)이거나 기회로서 대응이 필요한
경우 구체 대응 방안을 수립하고 사업계획에 반영한다.
5.6.4 대응 방안 수립 시에는 적절한 기한 내에 완성되도록 하고, 달성 가능(Achievable)
한 방안으로서, 목표 달성 여부의 측정가능(Measurable)한 것이 되도록 한다
5.6.5 Risk 대응방안 수립 결과는 RISK 분석표에 기록, 총무팀에 제출, 총무팀은 경영진에 보고한다.
5.7 리스크 대응계획 실행
5.7.1 각 팀은 다음을 포함하여 Risk 대응방안을 실행하여야 한다.
(1) 관련 프로세스/시스템 개정 또는 개선
(2) 관련 물적 자원 확보 또는 변경
(3) 관련 인원 훈련 및 이해 여부 확인
(4) 기타 취약성의 보완
5.7.2 각 팀은 대응방안의 실행 과정 및 완료 여부를 모니터링 하여야 한다.
또한 실행 결과를 보고하여야 한다.
5.8 사업 연속성계획(BCP) 수립
5.8.1 각 팀은 중점관리 대상으로서 Risk 대응 방안이 “ 비상계획(Contingency Plan)인
경우 사업연속성 계획(BCP-Business Continuity Plan)을 수립하여야 한다.
5.8.2 사업연속성 계획(BCP) 에는 중점 관리대상 활동에 대하여 위협이 현실화 한 경우
어떻게 신속한 복구 및 업무 재개가 되도록 할 것인가의 계획이어야 하며, 최악의
상황을 고려하여 계획을 수립하여야 한다.
5.8.2 사업연속성 계획에는 다음 사항이 포함되어야 한다.
- 핵심 설비 고장,공급자 운영 중단, 자연 재해, 유틸리티 중단, 노동력 부족 또는
인프라 중단 등
5.8.3 사업연속성 계획은 중단 사건 발생 시 누가, 어떤 자원을 이용하여, 어떤 방법으로
신속히 복구 및 업무 재개를 할 것인지를 나타내어야 한다.
5.8.4 사업연속성 계획에는 고객 운영에 영향을 주는 모든 상황의 정도와 기간에 대한
고객 통보 절차를 포함하여야 하며, 적절한 시뮬레이션을 포함하여 사업 연속성
계획의 효과성을 주기적으로 테스트하여야 한다.
