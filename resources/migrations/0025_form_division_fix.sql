UPDATE forms SET scope = '공통'
  WHERE scope IS NULL OR scope NOT IN ('공통', '조관', '인발', '필라넥', 'AM', '쇼바');

-- 약자 접미사 기반 사업부 확정 (양식명 (-조)/(-인)/(-필)/(-쇼바))
UPDATE forms SET scope = '조관'   WHERE code IN ('L2100-02', 'L2100-03', 'L2100-04', 'L2100-05');  -- (-조)
UPDATE forms SET scope = '인발'   WHERE code = 'L2100-01';                                          -- (-인)
UPDATE forms SET scope = '필라넥' WHERE code IN ('H2100-01', 'J1103-01');                           -- (-필라)
UPDATE forms SET scope = '쇼바'   WHERE code IN ('L2100-06', 'L2100-10');                           -- (-쇼바)
