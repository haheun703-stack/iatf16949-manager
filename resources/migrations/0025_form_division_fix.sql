--     'common' 잔재로 남는 불일치 발생. 유효 사업부 라벨이 아닌 모든 값 → '공통' 확정.
--     (사용자가 picker로 지정한 유효 라벨은 보존)
-- (2) 약자 분류: 0024는 풀네임만 잡아 약자 접미사(-조/-인/-필/-쇼바) 5건을 놓침.
--     양식명에 사업부 약자가 박힌 전체 9건을 확정(조관4·인발1·필라넥2·쇼바2).
