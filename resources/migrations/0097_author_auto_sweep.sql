-- 대상 = 결재란 '작성'(25) + '작성자'(24) text 필드 49건. 전부 문서 작성 주체(교차검증:
--   '작성'은 검토/승인 동반 22개 양식 소속, '작성자'는 대장·보고서의 작성 주체). auto 로 전환하면
--   수동 입력이 막히고 활성 사용자로 자동채움 → 남의 이름·빈칸 유출 구멍 제거.
-- 제외 = 검토·승인·성명·평가자·확인·담당자(본인 자동채움 대상 아님 — 상급자/타인이 결재).
--
-- type='auto'  : 자동채움 필드(검증 제외 + 렌더 readonly). placeholder '로그인 사용자' =
--                meta default·클라이언트 주입의 판별 표식(/사용자/). field_class='frame' :
--                auto 는 사람이 입력하는 fact 가 아니라 시스템 채움 → frame 통일(기존 auto 작성자와 일치).
--   ⚠️ 실제 자동채움 값은 코드에서: form-handlers meta default(defaultAuthor 폴백 제거) +
--      formStore/FormCanvas(활성 사용자 주입, 미선택 시 빈값). 이 마이그는 대상 지정만.
--
-- 멱등: type='text' 조건(재적용 시 이미 auto → 0행). BEGIN/COMMIT 없음(migrate.ts 트랜잭션).
