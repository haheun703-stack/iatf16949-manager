-- ── 결재란 작성/작성자(text) 49건 → auto 자동채움 ──
UPDATE form_fields
SET type='auto', field_class='frame', placeholder='로그인 사용자'
WHERE TRIM(label) IN ('작성','작성자') AND type='text';

-- ── 이미 auto 지만 placeholder 없어 자동채움 반쪽인 본인 기입 필드 표식 보정 ──
-- 0090(P7 셀맵)에서 auto 로 지정됐으나 '로그인 사용자' 표식이 없어 meta default·클라이언트
-- 주입 판별(/사용자/)에 안 걸리던 것들: L4102-02 작성자, 검사자·작업자·확인자·담당자 등.
-- '본인이 검사/작업/확인/담당한 사실 = 활성 사용자'라 자동채움 대상. 발행번호·문서번호류(자동부여)는
-- 라벨이 목록에 없어 제외됨. (위 스윕에서 방금 auto+ph 세팅된 작성/작성자는 ph null 아니라 스킵.)
UPDATE form_fields
SET placeholder='로그인 사용자'
WHERE type='auto' AND (placeholder IS NULL OR placeholder='')
  AND TRIM(label) IN ('작성','작성자','보고자','검사자','작업자','확인자','담당자');
