6.2.2 생산기술팀장은 관리번호를 설비전면에 각인 또는 식별표 부착하여 식별이 용이하도록
하여야 한다.
6.2.3 고객이 지급한 설비인 경우 ''설비관리대장''의 비고란에 고객명을 기록하고, 설비에
고객지급품임을 알수 있도록 고객명을 기록하여 식별한다.
6.2.4 설비번호부여 기준
(1)(2) : 회사약호(TC)
(3)(4) : 분류번호(P1)
(5)(6) : 설비약호 2자리
(7) : 일련번호
6.3 설비관리책임자 지정
6.3.1 설비관리 책임자는 생산기술팀장으로 다음과 같은 업무를 수행하여야 한다.
(1) 설비이력카드 기록 및 보관
(2) 설비의 점검기준 수립
(3) 설비의 배치에 따른 이동관리
(4) 설비의 정기점검 및 보전계획의 수행
(5) 설비의 고장과 조치에 대한 보고
(6) 설비 프로그램 빽업 관리 - 생산기술팀 전용 노트북(보안 스티커,비번)
(7) 기타 설비관리에 관한 사항
6.3.2 설비사용담당자는 제조설비를 사용하는 작업자를 의미하며 다음과 같은 업무를 수행한다.
(1) 설비의 운전
(2) 설비고장의 보고
(3) 설비의 성능 및 정도 유지에 이상 징후가 있을 경우 설비점검 요청
(4) 일상점검 실시 및 기록 보고
(5) 경미한 고장수리 및 기록보고
(6) 기타 필요한 사항
6.4 설비의 보전
6.4.1 일상보전
(1) 생산기술팀장은 일상점검항목을 설정하여 ''설비 일상점검표''를 작성하여 작업자에게 배포
하여야 한다.
(2) 작업자는 설비의 일상점검항목에 따라 설비의 이상유무를 확인하여야 한다.
(3) 설비이상 발견시 6.5항의 절차에 따라 처리한다.
6.4.2 정기보전
생산팀장은 년,월 설비점검 계획서에 따라 점검을 실시하여야 한다.
(1) 년간보전계획
가. 생산기술팀장은 전년도의 일상(정기)점검, 자산가치, 고장빈도 및 고장내용을 기초로 연간
사업계획 수립시 설비보전목표를 설정하고 "년간 설비점검 계획서"를 작성하여 대표이사의
승인을 받는다.
나. 설비보전계획은 보전의 효과를 높이기 위해 보전효과가 큰 설비부터 보전계획에 포함시킨다
(2) 월간보전계획
가. 생산기술팀장은 년간점검계획, 일상점검과 전월 미결된 조치등을 포함하여 ''월간 설비점검
계획서''를 작성하여 예방보전을 실시하고 ''보전업무일지''에 기록을 유지한다.
나. 점검 결과 이상이 있는 경우 6.5.2항의 절차에 따라 수리를 하고 이력카드에 이력을 유지한다.
6.5 설비의 보수
6.5.1 설비이상 및 고장발견, 접수
(1) 작업자는 설비의 운전 또는 점검중 설비의 이상이나 고장을 발견하면 구두 또는 유선
으로 생산팀장에게 보고하고, 생산팀장은 생산기술팀에 설비이상을 통보한다.
(2) 생산기술팀장은 설비 정기점검중 이상 발견 또는 설비 사용 담당자로부터 설비이상에
대하여 접수를 받으면 "설비고장 접수 및 처리대장"에 기록한다.
6.5.2 설비수리
(1) 생산기술팀장은 설비이상에 대하여 확인, 조치방안을 수립하고 이상조치를 하여야한다.
조치방안(설비수리) 투입 인원은 항시 2인 1조 운영 및 조작 판넬에 조작금지 명판을 필히
설치 후 수리 작업을 실시하여 안전사고를 미연에 방지 한다.
(보전 업무 일지 내 정,부 두명에 대한 성명을 명기하여, 2인 1조 운영에 대한 이력기록)
(2) 설비가 하자보증 기간내에 발생된 고장에 대해서는 설비제작업체에 통보하여 서비스
(A/S)를 받는다.
(3) 생산기술팀장은 30분이내에 즉시 조치가 가능한 이상에 대해서는 즉시 조치하고
"업무일지"에 조치 결과를 기록 유지한다.
(4) 30분 이상의 휴지가 발생한 경우 생산일정등을 고려하여 여유가 있으면 보수를
실시하고, 생산여유가 없는 경우 응급조치후 월 업무계획에 반영하여 보수될 수
있도록 한다. 단 설비, 여력, 기술부족으로 자체 보수가 불가능하면 외주업체를
선정하여 보수를 한다.
(5) 생산기술팀장은 30분 이상 휴지가 발생한 고장에 대해 "장비고장,수리 보고서"로
공장장에게 보고하고, 일일 보수, 수리 및 점검내용이 제품의 품질에 중요한
영향을 미치는 경우와 중요 부품의 교환일 경우 "설비이력카드"에 기록을 유지한다.
6.6 보전 자료분석 및 활용
(1) 생산기술팀장은 분석된 보전 자료를 차기 보전계획수립 및 보전활동에 활용될 수
있도록 한다.
(2) 생산팀장은 분석된 보전자료를 차기 설비 제작시 반영한다.
6.7 운휴 설비
(1)생산 아이템 감소 및 단종등으로 인한 설비 비가동이 장기화 될시 생산팀장은 설비에 대하여
운휴설비 지정 또는 설비 폐기등을 결정하여야 한다.
(2) 운휴 설비 결정시 생산 팀장은 운휴설비에 대하여 명판 부착, 식별관리를 하여야하며, 설비
주요 금형,치구조작, 판넬등에 대하여 오염을 방지 할수 있는 후속 조치를 취하여야 한다.
(오염 방지 예시 : 방수포 덮게 사용 , 랩 포장 , 주요 장비 해체 이동 보관 등)
(3)설비 폐기 결정시에는 6.8항을 기준으로 한다.
6.8 설비 폐기 결정
(1) 생산기술팀장은 설비의 노후로 제품생산 또는 품질에 영향을 주거나 공정변경등으로
설비가 불필요한 경우는 폐기품의서를 작성하여 대표이사에게 보고한다.
(2) 대표이사는 해당설비의 공정능력 평가자료, 보전자료 및 보전금액, 기술사양 등을
정밀 검토하여 폐기하는 것이 적절하다고 판단되면 폐기를 승인한다.
6.9 설비의 폐기
(1) 생산기술팀장은 해당설비 이력카드를 정리하고, 폐기품의서를 관리팀에 인계한다.
(2) 경리팀장은 폐기 승인된 제조 설비를 정리하여 폐기품의서에 폐기 감가상각 충당금을
기록하여 회계처리 한다.
(3) 생산기술팀장은 고객 지급 설비의 폐기는 고객과 협의, 고객의 승인을 득한후 폐기
할 수 있도록 한다.
(4) 경리팀장은 폐기 승인된 제조설비를 고정자산에서 제적한다.

