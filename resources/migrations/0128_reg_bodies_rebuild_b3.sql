협력업체와 협의를 통하여 서로의 이해와 납득 가능한 범위내에서 부품 가격을 결정한다.
(3) 구매담당은 업체와 결정된 가격을 협력업체 단가 결정 품의서를 작성하여 대표이사의
승인을 득한다.
