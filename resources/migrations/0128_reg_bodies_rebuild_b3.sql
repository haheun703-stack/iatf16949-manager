(2) 사내 자체 검정인 경우는 구간별 3회 반복하여 측정하고, 측정결과가 사외검교정
결과 합격인 계측기의 3회 반복 측정 결과와 비교하여 측정 정밀도 및 정확도가 5%
이내 일 경우 합격으로 한다.
(3) 품질보증팀장은 합부판정 결과를 "교정검사 성적서" 또는 "계측기 이력카드"에 기록하여
이력으로 관리한다.
5.8.4 합격 계측기 관리
(1) 외부 공인기관의 교정검사에서 합격한 계측기는 공인기관 발행의 스티커를 계측기에
부착하여 관리한다.
(2) 사내 교정검사, 점검 및 측정시스템 평가 결과 합격한 계측기는 사내 교정 검사 필증
스티커를 부착하여 관리한다.
(3) 품질보증팀장은 사내,외 교정검사가 완료된 계측기에 대하여 측정시스템 평가
대상 계측기에 대해서는 측정시스템 평가를 실시하고, 그 결과를 게이지 R&R Report에
기록한다.
5.8.5 부적합 계측기 관리
(1) 유효기간의 경과, 교정검사 필증 스티커의 미 부착 및 교정검사 결과 부적합 판정된
계측기는 즉시 회수한다.
(2) 부적합 계측기는 수리 또는 교정한 다음 교정검사를 받아 합격 판정을 받은후 저등급
으로 격하하여 사용한다.
5.8.6 검사 유효성 평가
(1) 교정검사 결과 부적합 계측기가 있는 경우, 품질보증팀장은 해당 계측기로
측정한 검사항목이 제품에 미치는 영향과 부적합 발생시기 등을 조사하여 이전에 실시한
검사의 유효성 및 조치방안을 수립하여 대표이사의 승인으로 실행한다.
(2) 부적합 계측기 사용으로 인하여 기 출하된 제품의 품질에 의문이 있는 경우, 개발/
품질보증팀장은 상세내역을 문서화하여 고객에게 통보하고 협의결과에 따라 조치한다.
(3) 품질보증팀장은 조사결과, 조치방안 및 결과에 대해 보고서를 작성하여 보고한다.
5.9 분실/파손 통보
(1) 사용팀장은 사용 계측기가 분실/파손이 발생할 경우 품질보증팀장에게 분실신고
및 수리를 의뢰한다.
(2) 분실 계측기에 대하여 사용팀장은 즉시 대체 계측기를 구입하여야 한다.
(3) 품질보증팀장은 필요시 대체 계측기 구입전까지 예비 계측기를 지원한다.
5.10 수리, 폐기
(1) 품질보증팀장은 교정검사결과 부적합 계측기 또는 파손 신고 접수된 계측기 중
수리가능한 계측기는 수리 및 검·교정을 실시하여 사용팀으로 반송하고, 수리 불가능시
에는 폐기하고 사용팀에 통보한다.
(2) 폐기 통보를 받은 사용팀장은 신규 구입한다.
5.11 일상점검
(1) 품질보증팀장은 측정실 담당자에게 1회/일 계측기 이상 여부에 대하여 점검 후
체크시트에 기록관리가 될수 있도록 관리한다.
5.11 기록 유지
품질보증팀장은 "계측기 관리대장"과 "계측기 관리카드"를 기록관리 규정에 따라
보관, 관리한다.
