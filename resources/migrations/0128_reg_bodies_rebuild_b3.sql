처리한다. 단, 미승인업체는 『협력업체 관리규정』에 따라 선정 평가후 적격하다고
판단시 외주처리 한다.
(3) 원,부자재가 고객의 유,무상 지급품인 경우 고객발주량을 고려하여 매월''사급 신청서''를
