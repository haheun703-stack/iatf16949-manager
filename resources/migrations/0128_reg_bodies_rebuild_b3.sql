개발담당은 고객으로부터 도면을 접수하면, 접수인을 스템핑한 후 ''도면관리대장''에
등록하고, 바인더에 파일링한다.
5.3 원도의 보관 및 활용
5.3.1 보관
(1) 각 사업부 개발팀장은 모든 제품 관련 도면에 대한 사내·외 기밀유지를 위하여
대외비로 취급, 보관한다.
(2) 도면의 보관장소 및 보관환경은 화재, 수해, 해충 등에 대한 대책을 고려한 위치에
비치하여 필요시, 즉시 반출할 수 있도록 보관한다.
5.3.2 최신 유효도면의 구분 및 배포
(1) 각 사업부 개발팀 개발담당은 고객승인이 확정된 양산용 도면은 전부 유효도면이므로
각 사업부 개발팀에서 통합관리하는 것을 원칙으로 하나 배포 필요시에는 ''도면관리대장''에
기록하고, 각 팀 또는 협력업체에 배포하며, 양산용 도면의 추가 등록이 있을시 또는
설계변경이 있을 때마다 ''도면관리대장''을 갱신한 후 관련팀이 열람할 수 있도록 비치한다.
(2) 도면철에 보관된 도면은 유효도면과 구도면의 구분을 명확히 식별할 수 있도록
구도면에는 ''구본''에 식별표시를 한다.
5.3.3 도면의 보관 및 활용
(1) 각 사업부 개발팀은 바인더 파일에 최근 배포된 유효 도면이 가장 위쪽(앞쪽)에서 확인될 수
있도록 철하고 ''도면관리대장''에 E.O NO. 기재하여 구본과 혼동이 없도록 한다.
(2) 금형 및 장비, 제작, 샘플 또는 제품이 제작,자재준비 등 도면의 활용 시, 각 사업부 개발팀
